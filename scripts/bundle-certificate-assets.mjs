/**
 * Bundles certificate HTML/CSS assets into TypeScript string modules
 * for Supabase Edge Functions (only .ts files are shipped to runtime).
 *
 * Usage: node scripts/bundle-certificate-assets.mjs
 */

import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ASSETS_DIR = join(__dirname, "../supabase/functions/_shared/certificate-assets");
const LOGO_SOURCE = join(__dirname, "../src/assets/icon.png");
const LOGO_PREVIEW_DIR = join(__dirname, "../certificates/shared/assets");
const LOGO_PREVIEW = join(LOGO_PREVIEW_DIR, "logo-icon.png");

const ASSETS = [
  { source: "foundation-certificate.html", exportName: "foundationCertificateHtml" },
  { source: "practitioner-certificate.html", exportName: "practitionerCertificateHtml" },
  { source: "expert-certificate.html", exportName: "expertCertificateHtml" },
  { source: "certificate-base.css", exportName: "certificateBaseCss" },
  { source: "certificate-dark-theme.css", exportName: "certificateDarkThemeCss" },
  { source: "certificate-dark-v2.css", exportName: "certificateDarkV2Css" },
];

const HEADER =
  "// AUTO-GENERATED by scripts/bundle-certificate-assets.mjs — do not edit\n";

for (const { source, exportName } of ASSETS) {
  const sourcePath = join(ASSETS_DIR, source);
  let contents;
  try {
    contents = readFileSync(sourcePath, "utf8");
  } catch {
    console.error(`Missing source file: ${sourcePath}`);
    process.exit(1);
  }

  if (!contents.trim()) {
    console.error(`Empty source file: ${source}`);
    process.exit(1);
  }

  const outName = `${source}.ts`;
  const outPath = join(ASSETS_DIR, outName);
  const outBody = `${HEADER}export const ${exportName} = ${JSON.stringify(contents)};\n`;
  writeFileSync(outPath, outBody, "utf8");
  console.log(`Wrote ${outName}`);
}

// Bundle logo as base64 data URI for PDF rendering (no external fetch)
let logoBytes;
try {
  logoBytes = readFileSync(LOGO_SOURCE);
} catch {
  console.error(`Missing logo file: ${LOGO_SOURCE}`);
  process.exit(1);
}

const logoDataUri = `data:image/png;base64,${logoBytes.toString("base64")}`;
const logoOutPath = join(ASSETS_DIR, "logo-icon.base64.ts");
writeFileSync(
  logoOutPath,
  `${HEADER}export const logoIconDataUri = ${JSON.stringify(logoDataUri)};\n`,
  "utf8",
);
console.log("Wrote logo-icon.base64.ts");

// Copy logo for local HTML preview
mkdirSync(LOGO_PREVIEW_DIR, { recursive: true });
copyFileSync(LOGO_SOURCE, LOGO_PREVIEW);
console.log("Copied logo-icon.png for local preview");

console.log("Done — bundled 6 certificate assets + logo.");
